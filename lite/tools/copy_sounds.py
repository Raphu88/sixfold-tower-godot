#!/usr/bin/env python3
"""Copies the sounds Six Towers LITE plays from the full game, and writes
lite/scripts/sounds.gd (the list audio.gd loads).

LITE is its own Godot project, so it can't reach the full game's files: it
keeps copies of only the sounds it uses. Which ones is worked out from LITE's
own scripts: every sfx("name") in them, each monster's and beast's cries
(hurt_, kill_, warn_ and the beasts' roar_), each magic's "sound", and the
music and ambiences in MUSIC below. Run it again after changing which sounds
LITE plays, or after rebuilding the full game's sounds (tools/build_audio.py):

    python3 lite/tools/copy_sounds.py
"""
import os
import re
import shutil

LITE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FULL = os.path.dirname(LITE)
MUSIC = ["music", "ambience_train"] + ["ambience_" + t for t in
         ["gryphon", "kraken", "wyvern", "manticore", "firebird", "chimera"]]


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def wanted():
    names = set()
    scripts = os.path.join(LITE, "scripts")
    for f in os.listdir(scripts):
        if f.endswith(".gd") and f != "sounds.gd":
            for m in re.finditer(r'sfx\("([a-z_]+)"', read(os.path.join(scripts, f))):
                if not m.group(1).endswith("_"):
                    names.add(m.group(1))
    data = read(os.path.join(scripts, "data.gd"))
    order = re.search(r"const ORDER := \[(.*?)\]", data).group(1)
    towers = re.findall(r'"([a-z]+)"', order)
    monsters_block = data[data.index("static var MONSTERS"):data.index("}\n", data.index("static var MONSTERS"))]
    monsters = re.findall(r'^\t"([a-z]+)": \{', monsters_block, re.M)
    for id in monsters + towers:
        names.update(["hurt_" + id, "kill_" + id, "warn_" + id])
    for t in towers:
        names.add("roar_" + t)
    names.update(re.findall(r'"sound": "([a-z_]+)"', data))
    return sorted(names)


def bank():
    text = read(os.path.join(FULL, "scripts", "sound_bank.gd"))
    sfx_text = text[text.index("const SFX"):text.index("const MUSIC")]
    sfx = {m.group(1): re.findall(r'"(res://[^"]+)"', m.group(2))
           for m in re.finditer(r'^\t"([a-z_0-9]+)": \[(.*?)\]', sfx_text, re.M)}
    music = dict(re.findall(r'^\t"([a-z_]+)": "(res://[^"]+)"', text[text.index("const MUSIC"):], re.M))
    return sfx, music


def copy(res_path):
    rel = res_path.replace("res://", "")
    dest = os.path.join(LITE, rel)
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    shutil.copy2(os.path.join(FULL, rel), dest)
    # Its import settings too (the full game's compression and looping).
    if os.path.exists(os.path.join(FULL, rel + ".import")):
        shutil.copy2(os.path.join(FULL, rel + ".import"), dest + ".import")
    return res_path


def main():
    sfx, music = bank()
    out_sfx, missing = {}, []
    for name in wanted():
        if name in sfx:
            out_sfx[name] = [copy(p) for p in sfx[name]]
        else:
            missing.append(name)
    out_music = {k: copy(music[k]) for k in MUSIC if k in music}
    # Old copies LITE no longer plays.
    keep = {p.replace("res://", "") for v in out_sfx.values() for p in v} | {p.replace("res://", "") for p in out_music.values()}
    for sub in ["assets/audio/sfx", "assets/audio/music"]:
        d = os.path.join(LITE, sub)
        for f in os.listdir(d) if os.path.isdir(d) else []:
            base = f[:-len(".import")] if f.endswith(".import") else f
            if os.path.join(sub, base) not in keep:
                os.remove(os.path.join(d, f))
    lines = ["extends RefCounted",
             "## Generated by tools/copy_sounds.py (copies of the full game's sounds). Do not edit by hand.",
             "", "const SFX := {"]
    lines += ['\t"%s": [%s],' % (k, ", ".join('"%s"' % p for p in v)) for k, v in out_sfx.items()]
    lines += ["}", "", "const MUSIC := {"]
    lines += ['\t"%s": "%s",' % (k, v) for k, v in out_music.items()]
    lines += ["}", ""]
    with open(os.path.join(LITE, "scripts", "sounds.gd"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("%d sounds, %d music loops copied" % (len(out_sfx), len(out_music)))
    if missing:
        print("not in the full game's sound bank (they stay silent):", ", ".join(missing))


if __name__ == "__main__":
    main()
